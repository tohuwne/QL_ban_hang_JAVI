const assert=require('assert/strict');
const {schema,importModules}=require('../Admin/Backend/services/import-schema');
const {validate,groups}=require('../Admin/Backend/services/import-validation');
const workbook=require('../Admin/Backend/services/import-workbook');
const ExcelJS=require('../node_modules/exceljs');
const def=schema['don-hang'];
const customer={MaKH:'KH000001',TenKH:'Khách cũ',SoDTKH:'0901111111',GioiTinhKH:'Nam',MaLoaiKH:'L01',DiaChiKH:'',EmailKH:null};
const lookups={customers:[customer],MaNV:[{id:'NV000001',name:'NV'}],MaSP:[{id:'CFH01',name:'Cà phê'}],MaLoaiKH:[{id:'L01',name:'Khách lẻ'}]};
const base={MaDH:'DON01',MaKH:'KH000001',MaNV:'NV000001',MaSP:'CFH01',SoLuong:'1',GiamGiaSP:'0',TrangThaiDonHang:'Chờ giao'};
const row=(values,line=2)=>({line,values,errors:[],parseErrors:[]});
const check=rows=>validate(def,rows,[],lookups,'skip');
(async()=>{
 assert(importModules.has('don-hang'));assert(!importModules.has('hoa-don'));assert(!def.columns.find(c=>c.key==='MaKH').ref);
 assert(!def.columns.some(c=>c.key==='NhomChungTu'));
 let grouped=check([row(base),row({...base,MaSP:'CFH02'},3),row({...base,MaDH:'DON02'},4)]);
 assert.equal(groups(def,grouped).length,2);assert.equal(groups(def,grouped)[0].length,2);
 assert.deepEqual(grouped.map(r=>r.stt),[1,2,3]);
 let rows=check([row(base)]);assert.deepEqual(rows[0].errors,[]);assert.equal(rows[0].customerSnapshot.MaKH,customer.MaKH);
 rows=check([row({...base,MaKH:'KH999999'})]);assert(rows[0].errors.some(e=>e.includes('Mã khách hàng không tồn tại')));
 rows=check([row({...base,SoDTKH:'0902222222'})]);assert(rows[0].errors.some(e=>e.includes('không khớp')));
 const fresh={...base,MaKH:'',TenKH:'Khách mới',SoDTKH:'0902222222'};
 rows=check([row(fresh)]);assert.deepEqual(rows[0].errors,[]);assert.equal(rows[0].data.MaLoaiKH,'L01');
 rows=check([row({...fresh,TenKH:''})]);assert(rows[0].errors.some(e=>e.includes('bắt buộc')));
 rows=check([row({...fresh,SoDTKH:customer.SoDTKH})]);assert(rows[0].errors.some(e=>e.includes(customer.MaKH)));
 rows=check([row(fresh),row({...fresh,MaDH:'DON02'},3)]);assert(rows.every(r=>!r.errors.length));
 rows=check([row(fresh),row({...fresh,TenKH:'Tên khác',MaDH:'DON02'},3)]);assert(rows.every(r=>r.errors.some(e=>e.includes('không thống nhất'))));
 const book=new ExcelJS.Workbook();await book.xlsx.load(await workbook.template(def,lookups));
 const column=def.columns.findIndex(c=>c.key==='MaKH')+1;assert.notEqual(book.getWorksheet('Nhap lieu').getCell(2,column).dataValidation.type,'list');
 assert(def.columns.some(c=>c.newCustomer&&c.key==='TenKH'));
 console.log('PASS: typed customer code, unknown-code rejection, conditional new-customer rules, duplicate phone checks, consistent reuse and no customer dropdown.');
})().catch(e=>{console.error(e);process.exitCode=1;});
