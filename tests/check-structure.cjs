const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const vm = require('vm');
const frontendFile = require('./frontend-path.cjs');
const paths = require('../Shared/Backend/config/paths');
const walk = dir => fs.readdirSync(dir, {withFileTypes:true}).flatMap(entry =>
  entry.isDirectory() ? walk(path.join(dir, entry.name)) : [path.join(dir, entry.name)]);
const problems = [];
for (const folder of ['Admin/Frontend', 'Admin/Backend', 'User/Frontend', 'User/Backend', 'Shared']) {
  assert(fs.statSync(folder).isDirectory(), folder);
}
assert(!fs.existsSync('be') && !fs.existsSync('fe'), 'Legacy source folders must be removed');
for (const file of [...walk('Admin'), ...walk('User'), ...walk('Shared')]) {
  if (file.endsWith('.js')) {
    const source = fs.readFileSync(file, 'utf8');
    try { new vm.Script(source, {filename:file}); } catch (err) { problems.push(err.message); }
    for (const match of source.matchAll(/require\(['"](\.[^'"]+)['"]\)/g)) {
      try { require.resolve(path.resolve(path.dirname(file), match[1])); }
      catch { problems.push(file + ': missing module ' + match[1]); }
    }
  }
  if (!file.endsWith('.html')) continue;
  const source = fs.readFileSync(file, 'utf8');
  const url = '/'+(file.startsWith('Admin') ? 'admin/' : 'landing_page/')+path.basename(file);
  for (const match of source.matchAll(/(?:src|href)=["']([^"']+)["']/g)) {
    const value = match[1];
    if (/^(?:https?:|data:|mailto:|tel:|#|javascript:)/.test(value) || value.includes('${')) continue;
    const target = new URL(value, 'http://javi.test' + url).pathname;
    // Generated by the server for the customer/admin login context.
    if (target === '/runtime-config.js') continue;
    if (!/\.(?:html|css|js|png|jpe?g|svg|webp|woff2?)$/i.test(target)) continue;
    if (target === '/admin/login.html' || target === '/admin/mua-hang.html') continue;
    const physical = frontendFile(target);
    if (!physical || !fs.existsSync(physical)) problems.push(file + ': missing URL ' + target);
  }
  for (const match of source.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) {
    if (match[1].trim()) {
      try { new vm.Script(match[1], {filename:file}); }
      catch (err) { problems.push(err.message); }
    }
  }
}
assert.equal(problems.length, 0, problems.join('\n'));
assert(fs.existsSync(path.join(paths.adminFrontend, 'san-pham.html')));
assert(fs.existsSync(path.join(paths.sharedFrontend, 'images/logo-javi-auth.png')));
assert(fs.existsSync('Admin/Backend/templates/import'));
console.log('PASS: source layout, backend module resolution, JavaScript syntax and frontend local asset/page paths');
